"""Export a SchemaForge project as a SQL script for SQLite, PostgreSQL, MySQL
or Oracle (Oracle is just one optional target).  Besides tables, constraints,
indexes, views and data, the script can include the course's "advanced" parts
generated per dialect: an audit trigger, a cursor-based report procedure,
GRANT statements and a COMMIT / ROLLBACK / SAVEPOINT demo."""
import re

from engine import sql_type

DIALECTS = ["sqlite", "postgres", "mysql", "oracle"]


def _qi(name, d):
    if d == "mysql":
        return f"`{name}`"
    if d == "oracle":
        return name.upper()
    return f'"{name}"'


def _type(c, d):
    t = c["type"]
    if d == "sqlite":
        return "INTEGER" if t == "INT" else sql_type(c)
    if t == "INT":
        return {"postgres": "INTEGER", "mysql": "INT", "oracle": "NUMBER(10)"}[d]
    if t == "VARCHAR":
        n = int(c.get("length") or 100)
        return f"VARCHAR2({n})" if d == "oracle" else f"VARCHAR({n})"
    if t == "TEXT":
        return {"postgres": "TEXT", "mysql": "TEXT", "oracle": "CLOB"}[d]
    if t == "DECIMAL":
        p, s = int(c.get("precision") or 10), int(c.get("scale") or 2)
        return {"postgres": f"NUMERIC({p},{s})", "mysql": f"DECIMAL({p},{s})", "oracle": f"NUMBER({p},{s})"}[d]
    if t == "FLOAT":
        return {"postgres": "DOUBLE PRECISION", "mysql": "DOUBLE", "oracle": "BINARY_DOUBLE"}[d]
    if t == "DATE":
        return "DATE"
    if t == "DATETIME":
        return {"postgres": "TIMESTAMP", "mysql": "DATETIME", "oracle": "TIMESTAMP"}[d]
    if t == "BOOLEAN":
        return {"postgres": "BOOLEAN", "mysql": "TINYINT(1)", "oracle": "NUMBER(1)"}[d]
    return t


def _lit(v, col, d):
    if v is None:
        return "NULL"
    t = col["type"]
    if t == "BOOLEAN":
        if d == "postgres":
            return "TRUE" if v else "FALSE"
        return "1" if v else "0"
    if t in ("INT", "FLOAT", "DECIMAL"):
        return str(v)
    s = str(v).replace("'", "''")
    if d == "oracle" and t == "DATE":
        return f"DATE '{s}'"
    if d == "oracle" and t == "DATETIME":
        return f"TIMESTAMP '{s}'"
    if d == "mysql":
        s = s.replace("\\", "\\\\")
    return f"'{s}'"


def _default(c, d):
    v = str(c["default"]).strip()
    if v.upper() in ("CURRENT_TIMESTAMP", "CURRENT_DATE"):
        if d == "oracle":
            return "SYSTIMESTAMP" if v.upper() == "CURRENT_TIMESTAMP" else "SYSDATE"
        return v.upper()
    if v.upper() == "NULL":
        return "NULL"
    if c["type"] == "BOOLEAN":
        on = v.lower() in ("1", "true", "yes")
        return ("TRUE" if on else "FALSE") if d == "postgres" else ("1" if on else "0")
    if re.fullmatch(r"-?\d+(\.\d+)?", v):
        return v
    return "'" + v.replace("'", "''") + "'"


def _check(c, d):
    ck = c["check"]
    col = _qi(c["name"], d)
    op, val = ck["op"], str(ck["value"]).strip()

    def lit(x):
        x = x.strip()
        return x if re.fullmatch(r"-?\d+(\.\d+)?", x) else "'" + x.replace("'", "''") + "'"
    if op == "BETWEEN":
        a, b = [p for p in val.split(",")]
        return f"CHECK ({col} BETWEEN {lit(a)} AND {lit(b)})"
    if op == "IN":
        return f"CHECK ({col} IN ({', '.join(lit(p) for p in val.split(',') if p.strip())}))"
    return f"CHECK ({col} {op} {lit(val)})"


def order_tables(specs):
    names = list(specs)
    done, out = set(), []
    while len(out) < len(names):
        progressed = False
        for n in names:
            if n in done:
                continue
            deps = {c["fk"]["table"] for c in specs[n]["columns"] if c["fk"]} - {n}
            if deps <= done:
                out.append(n)
                done.add(n)
                progressed = True
        if not progressed:
            out += [n for n in names if n not in done]
            break
    return out


def create_table(spec, d):
    t = spec["name"]
    pks = [c for c in spec["columns"] if c["pk"]]
    lines = []
    for c in spec["columns"]:
        parts = [_qi(c["name"], d), _type(c, d)]
        if c["auto"]:
            if d == "sqlite":
                lines.append(f"  {_qi(c['name'], d)} INTEGER PRIMARY KEY AUTOINCREMENT")
                continue
            if d == "mysql":
                parts.append("AUTO_INCREMENT")
            else:
                parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if c["default"] not in ("", None):
            parts.append("DEFAULT " + _default(c, d))
        if c["notnull"] and not c["auto"]:
            parts.append("NOT NULL")
        if c["unique"] and not c["pk"]:
            parts.append("UNIQUE")
        if c["check"]:
            parts.append(_check(c, d))
        lines.append("  " + " ".join(parts))
    if pks:
        lines.append("  PRIMARY KEY (" + ", ".join(_qi(c["name"], d) for c in pks) + ")")
    for c in spec["columns"]:
        fk = c["fk"]
        if fk:
            act = fk.get("on_delete", "NO ACTION")
            clause = ""
            if act == "CASCADE" or act == "SET NULL":
                clause = f" ON DELETE {act}"
            elif act == "RESTRICT" and d != "oracle":
                clause = " ON DELETE RESTRICT"
            lines.append(f"  FOREIGN KEY ({_qi(c['name'], d)}) REFERENCES {_qi(fk['table'], d)} "
                         f"({_qi(fk['column'], d)}){clause}")
    return f"CREATE TABLE {_qi(t, d)} (\n" + ",\n".join(lines) + "\n);"


def _view_sql(sql, d):
    if d == "mysql":
        return re.sub(r'"([A-Za-z_]\w*)"', r"`\1`", sql)
    if d == "oracle":
        return re.sub(r'"([A-Za-z_]\w*)"', lambda m: m.group(1).upper(), sql)
    return sql


# ---- per-dialect advanced objects ---------------------------------------
def audit_objects(specs, d):
    audited = [s for s in specs.values() if s.get("audit")]
    if not audited or d == "sqlite":
        return []
    out = ["-- ---- Audit trail (triggers) ----"]
    if d == "postgres":
        out.append("""CREATE TABLE audit_log (
  audit_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name VARCHAR(60) NOT NULL,
  action     VARCHAR(10) NOT NULL,
  old_data   JSONB,
  new_data   JSONB,
  changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION fn_audit() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO audit_log(table_name, action, new_data) VALUES (TG_TABLE_NAME, 'INSERT', to_jsonb(NEW));
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    INSERT INTO audit_log(table_name, action, old_data, new_data) VALUES (TG_TABLE_NAME, 'UPDATE', to_jsonb(OLD), to_jsonb(NEW));
    RETURN NEW;
  ELSE
    INSERT INTO audit_log(table_name, action, old_data) VALUES (TG_TABLE_NAME, 'DELETE', to_jsonb(OLD));
    RETURN OLD;
  END IF;
END;
$$ LANGUAGE plpgsql;
""")
        for s in audited:
            out.append(f'CREATE TRIGGER trg_{s["name"]}_audit AFTER INSERT OR UPDATE OR DELETE ON "{s["name"]}"\n'
                       f"  FOR EACH ROW EXECUTE FUNCTION fn_audit();")
    elif d == "mysql":
        out.append("""CREATE TABLE audit_log (
  audit_id   INT AUTO_INCREMENT PRIMARY KEY,
  table_name VARCHAR(60) NOT NULL,
  action     VARCHAR(10) NOT NULL,
  old_data   JSON,
  new_data   JSON,
  changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);""")
        for s in audited:
            t = s["name"]
            new = ", ".join(f"'{c['name']}', NEW.`{c['name']}`" for c in s["columns"])
            old = ", ".join(f"'{c['name']}', OLD.`{c['name']}`" for c in s["columns"])
            out.append(f"CREATE TRIGGER trg_{t}_ins AFTER INSERT ON `{t}` FOR EACH ROW\n"
                       f"  INSERT INTO audit_log(table_name, action, new_data) VALUES ('{t}', 'INSERT', JSON_OBJECT({new}));")
            out.append(f"CREATE TRIGGER trg_{t}_upd AFTER UPDATE ON `{t}` FOR EACH ROW\n"
                       f"  INSERT INTO audit_log(table_name, action, old_data, new_data) VALUES ('{t}', 'UPDATE', JSON_OBJECT({old}), JSON_OBJECT({new}));")
            out.append(f"CREATE TRIGGER trg_{t}_del AFTER DELETE ON `{t}` FOR EACH ROW\n"
                       f"  INSERT INTO audit_log(table_name, action, old_data) VALUES ('{t}', 'DELETE', JSON_OBJECT({old}));")
    elif d == "oracle":
        out.append("""CREATE TABLE audit_log (
  audit_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name VARCHAR2(60) NOT NULL,
  action     VARCHAR2(10) NOT NULL,
  row_info   VARCHAR2(4000),
  changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
""")
        for s in audited:
            t = s["name"].upper()
            def info(prefix):
                return " || ', ' || ".join(f"'{c['name']}=' || {prefix}.{c['name'].upper()}" for c in s["columns"])
            out.append(f"""CREATE OR REPLACE TRIGGER trg_{t}_audit
AFTER INSERT OR UPDATE OR DELETE ON {t}
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO audit_log(table_name, action, row_info) VALUES ('{t}', 'INSERT', {info(':NEW')});
  ELSIF UPDATING THEN
    INSERT INTO audit_log(table_name, action, row_info) VALUES ('{t}', 'UPDATE', {info(':NEW')});
  ELSE
    INSERT INTO audit_log(table_name, action, row_info) VALUES ('{t}', 'DELETE', {info(':OLD')});
  END IF;
END;
/""")
    return out


def cursor_procedures(specs, d):
    if d not in ("postgres", "oracle"):
        return []
    out = ["-- ---- Stored procedures with an explicit cursor (report every row) ----"]
    for s in specs.values():
        t = s["name"]
        if d == "postgres":
            out.append(f"""CREATE OR REPLACE PROCEDURE report_{t}() LANGUAGE plpgsql AS $$
DECLARE
  cur CURSOR FOR SELECT * FROM "{t}";
  rec RECORD;
  n   INTEGER := 0;
BEGIN
  OPEN cur;
  LOOP
    FETCH cur INTO rec;
    EXIT WHEN NOT FOUND;
    n := n + 1;
    RAISE NOTICE 'Row %: %', n, rec;
  END LOOP;
  CLOSE cur;
  RAISE NOTICE '% row(s) in {t}', n;
END;
$$;
-- CALL report_{t}();""")
        else:
            T = t.upper()
            body = " || ' | ' || ".join(f"TO_CHAR(r.{c['name'].upper()})" for c in s["columns"][:6])
            out.append(f"""CREATE OR REPLACE PROCEDURE report_{T} IS
  CURSOR c IS SELECT * FROM {T};
  n NUMBER := 0;
BEGIN
  FOR r IN c LOOP
    n := n + 1;
    DBMS_OUTPUT.PUT_LINE(n || ': ' || {body});
  END LOOP;
  DBMS_OUTPUT.PUT_LINE(n || ' row(s) in {T}');
END;
/
-- SET SERVEROUTPUT ON; EXEC report_{T};""")
    return out


def tcl_demo(specs, d):
    names = list(specs)
    if not names:
        return []
    t = _qi(names[0], d)
    begin = "START TRANSACTION;" if d in ("mysql", "postgres") else "-- (a transaction starts automatically)"
    return ["-- ---- Transaction control demo ----",
            f"-- {begin}", "-- SAVEPOINT before_change;", f"-- DELETE FROM {t};",
            "-- ROLLBACK TO SAVEPOINT before_change;   -- undo the delete", "-- COMMIT;"]


def export_sql(specs, data, dialect, views=None, grants=None, extras=True, include_data=True):
    d = dialect
    out = [f"-- SchemaForge export ({d})", ""]
    if d == "sqlite":
        out += ["PRAGMA foreign_keys = ON;", ""]
    ordered = order_tables(specs)
    for t in ordered:
        out.append(create_table(specs[t], d))
        for ix in specs[t]["indexes"]:
            u = "UNIQUE " if ix["unique"] else ""
            out.append(f"CREATE {u}INDEX {_qi(ix['name'], d)} ON {_qi(t, d)} ({', '.join(_qi(c, d) for c in ix['columns'])});")
        out.append("")
    if include_data:
        for t in ordered:
            cols = specs[t]["columns"]
            for row in data.get(t, []):
                vals = ", ".join(_lit(row[c["name"]], c, d) for c in cols)
                names = ", ".join(_qi(c["name"], d) for c in cols)
                out.append(f"INSERT INTO {_qi(t, d)} ({names}) VALUES ({vals});")
            if data.get(t) and d == "postgres":
                for c in cols:
                    if c["auto"]:
                        out.append(f"SELECT setval(pg_get_serial_sequence('\"{t}\"', '{c['name']}'), "
                                   f"(SELECT COALESCE(MAX(\"{c['name']}\"), 1) FROM \"{t}\"));")
            if data.get(t) and d == "oracle":
                out.append("-- (identity columns continue from 1; use ALTER TABLE ... MODIFY ... RESTART WITH if needed)")
        out.append("")
    for v in views or []:
        out.append(_view_sql(v["sql"], d).rstrip(";") + ";")
    if views:
        out.append("")
    if extras:
        for block in (audit_objects(specs, d), cursor_procedures(specs, d), tcl_demo(specs, d)):
            if block:
                out += block + [""]
    if grants and d != "sqlite":
        out.append("-- ---- Privileges (create the users/roles first) ----")
        for user, table, priv in grants:
            out.append(f"GRANT {priv} ON {_qi(table, d)} TO {_qi(user, d) if d != 'oracle' else user.upper()};")
        out.append("")
    return "\n".join(out)
